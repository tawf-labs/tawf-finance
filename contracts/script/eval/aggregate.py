#!/usr/bin/env python3
"""Turn raw CSVs in eval/raw into the published CSV tables and eval/RESULTS.md. Stdlib only."""
import csv, os, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
EVAL = os.path.normpath(os.path.join(HERE, "..", "..", "..", "eval"))
RAW = os.path.join(EVAL, "raw")

# Assumptions. Every price below is an assumption, not a measurement.
ETH_USD = {"low": 2000, "base": 3000, "high": 4000}
ARB_GWEI = {"low": 0.01, "base": 0.02, "high": 0.10}
L1_GWEI = {"low": 0.5, "base": 1.0, "high": 5.0}


def rows(name):
    with open(os.path.join(RAW, name)) as f:
        return list(csv.DictReader(f))


def usd(gas, gwei, eth):
    return gas * gwei * 1e-9 * eth


def fmt(n):
    return f"{int(n):,}"


def md(headers, body):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in body]
    return "\n".join(out)


def write_csv(name, headers, body):
    with open(os.path.join(EVAL, name), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(headers)
        w.writerows(body)


gas = rows("gas_per_op.csv")
adv = rows("adversarial.csv")
scale = rows("scale.csv")
sep_deploy = rows("sepolia_deploy.csv")
sep_life = rows("sepolia_lifecycle.csv")

# Table 1: gas per operation
gas_tbl = [(r["scenario"], r["operation"], int(r["gas"])) for r in gas]
write_csv("gas_per_op.csv", ["scenario", "operation", "local_gas"], gas_tbl)

sep_tbl = [(r["operation"], int(r["sepolia_gas_used"])) for r in sep_deploy + sep_life]
write_csv("sepolia_gas.csv", ["operation", "sepolia_gas_used"], sep_tbl)

# Table 2: cost per financing
happy = sum(g for s, _, g in gas_tbl if s == "happy")
deploy_total = sum(g for s, _, g in gas_tbl if s == "deploy")
sep_fin = sum(int(r["sepolia_gas_used"]) for r in sep_life if r["operation"] not in ("faucet", "usdc_approve"))
sep_dep = sum(int(r["sepolia_gas_used"]) for r in sep_deploy if r["operation"].endswith(".deploy"))
sc = {int(r["financings"]): r for r in scale}
cost_rows = []
for label, g in [
    ("Lifecycle, 4 fundings (local Cancun gas)", happy),
    ("Scale avg, 100 financings (3 to 5 fundings, local)", int(sc[100]["gas_per_financing"])),
    ("Scale avg, 1000 financings (3 to 5 fundings, local)", int(sc[1000]["gas_per_financing"])),
    ("Lifecycle, 1 funding (measured on Ethereum Sepolia)", sep_fin),
]:
    for net, gw in [("Arbitrum (assumed)", ARB_GWEI), ("Ethereum L1 (assumed)", L1_GWEI)]:
        cost_rows.append((label, net, g, *[round(usd(g, gw[k], ETH_USD["base"]), 4) for k in ("low", "base", "high")]))
write_csv("cost_per_financing.csv", ["lifecycle", "network", "gas", "usd_low_gas_price", "usd_base_gas_price", "usd_high_gas_price"], cost_rows)

write_csv("adversarial.csv", ["id", "attack", "target", "expected", "observed", "match", "enforcing_mechanism"],
          [(r["id"], r["attack"], r["target"], r["expected"], r["observed"], r["match"], r["enforcing_mechanism"]) for r in adv])
write_csv("scale.csv", list(scale[0].keys()), [list(r.values()) for r in scale])

blocked = sum(1 for r in adv if r["observed"] == "blocked")
gaps = [r for r in adv if r["observed"] == "allowed"]
mism = [r for r in adv if r["match"] != "yes"]

local_vs_sep = []
sep_by = {r["operation"]: int(r["sepolia_gas_used"]) for r in sep_deploy + sep_life}
loc_by = {r["operation"]: int(r["gas"]) for r in gas if r["scenario"] in ("deploy", "happy")}
for op_s, op_l in [("MockUSDC.deploy", "MockUSDC"), ("BondReceiptNFT.deploy", "BondReceiptNFT"), ("DealRegistry.deploy", "DealRegistry"),
                   ("RedemptionVault.deploy", "RedemptionVault"), ("createDeal", "createDeal"), ("approveDeal", "approveDeal"),
                   ("markMintable", "markMintable"), ("invest", "invest_first"), ("repay", "repay")]:
    local_vs_sep.append((op_s, fmt(loc_by[op_l]), fmt(sep_by[op_s]), f"{sep_by[op_s] / loc_by[op_l]:.1f}x"))

doc = f"""# Synthetic evaluation of the tawf.finance contracts

Generated by `contracts/script/eval/aggregate.py` from raw CSVs in `eval/raw/`. Every input is synthetic. There is no pilot, no real user and no real money.

## 1. Scope, and what the contracts do not do

The deployed contracts implement a BPRS financing sell-down pool, not a tranche disbursement escrow. They contain a role-gated state machine (`DealRegistry`), a USDC vault (`RedemptionVault`), soulbound receipts (`BondReceiptNFT`), a transfer compliance module and an ERC-4626 pooled vault.

They do **not** implement on-chain tranche release, evidence hash submission, verification, mismatch flagging, escalation or appeal, an AI agent signer, or a multisig. Those parts of the chapter's design are therefore **not evaluated here**. This evaluation measures what exists and maps it as follows.

| Chapter step | What was actually run |
|---|---|
| Register | `createDeal` by the BPRS officer role |
| Approve | `approveDeal` by the Sharia board role |
| Release tranche (proxy) | `markMintable`, then `invest` fundings from investor wallets. This is funding of the pool, not release to a client |
| Evidence, verify, mismatch, escalate, appeal | Not implemented on-chain, not run |
| Agent signer (proxy) | A key holding `OPS_ROLE` on the registry and vault. It matures, repays and defaults pools |
| Close | `repay`, `redeem` and automatic `completeDeal`. A second path runs `defaultDeal` and `claimDefault` |

## 2. Setup and assumptions

- Framework: Foundry (forge 1.5.1), solc 0.8.24, via_ir, optimizer 200 runs, evm cancun.
- Profile: `FOUNDRY_PROFILE=eval` (see `contracts/foundry.toml`). Isolate mode is on so each top level call is its own transaction. Gas comes from `vm.lastCallGas()`. Deployment gas is a `gasleft()` delta around `new`.
- Actors, each on its own key: admin, BPRS officer (`ORIGINATOR_ROLE`), Sharia board (`SHARIAH_ROLE`), AI agent signer (`OPS_ROLE`), auditor (no role, observer only), stranger, client (never an on-chain caller), investors.
- Contract source is unchanged. Tests, scripts and the `eval` profile are the only additions.
- Reproduce: `contracts/script/eval/RunEval.sh` (no keys, no network).
- Pricing assumptions. These are placeholders, not measurements. A web search for live Arbitrum and ETH prices returned only forecasts and one implausible figure, so none were verified:
  - ETH price: ${ETH_USD['base']:,} base. Sensitivity of ${ETH_USD['low']:,} and ${ETH_USD['high']:,} is easy to compute because cost scales linearly.
  - Arbitrum gas price: {ARB_GWEI['low']} / {ARB_GWEI['base']} / {ARB_GWEI['high']} gwei (low, base, high).
  - Ethereum L1 gas price: {L1_GWEI['low']} / {L1_GWEI['base']} / {L1_GWEI['high']} gwei (low, base, high).
  - The Arbitrum figure covers L2 execution gas only. It leaves out the L1 data posting fee, and it applies Foundry gas units, which are not ArbOS gas units.

## 3. Gas per operation (local, Foundry Cancun schedule)

{md(["scenario", "operation", "gas"], [(s, o, fmt(g)) for s, o, g in gas_tbl])}

Deploying all six contracts costs {fmt(deploy_total)} gas locally.

### 3.1 The same operations measured on Ethereum Sepolia

The stack was deployed to Ethereum Sepolia (chain 11155111) with a burner key, and one lifecycle was run there with that single key acting in every role. The node reported much higher gas for contract creation and storage writes than the local Cancun schedule. The Sepolia client at the time was reth 2.7.0, and its gas schedule is evidently not the one Foundry models. The cause was not investigated.

{md(["operation", "local gas", "Sepolia gas", "ratio"], local_vs_sep)}

Sepolia deploy total: {fmt(sep_dep)} gas. Sepolia lifecycle (1 funding, excluding faucet and approve): {fmt(sep_fin)} gas. Deployed addresses and transaction hashes are in `eval/raw/sepolia_deploy.csv` and `eval/raw/sepolia_lifecycle.csv`.

Takeaway for the chapter: gas numbers depend heavily on the client and fork rules. Treat the local table as a relative cost profile and not as a quote for any live network.

## 4. USD cost per financing

Columns show low, base and high gas price. ETH price is fixed at the base value.

{md(["lifecycle", "network", "gas", "USD low", "USD base", "USD high"], [(a, b, fmt(c), f"{d:.4f}", f"{e:.4f}", f"{f:.4f}") for a, b, c, d, e, f in cost_rows])}

One time deployment of the stack (local gas, {fmt(deploy_total)}) costs ${usd(deploy_total, ARB_GWEI['base'], ETH_USD['base']):.2f} at the Arbitrum base assumption.

## 5. Adversarial scenarios

{len(adv)} scenarios. {blocked} were blocked by an on-chain check. {len(gaps)} were allowed and are listed as known gaps. {len(mism)} did not match the expectation written before the run.

"Expected: allowed (known gap)" rows are not security passes. They record behavior the design currently permits.

{md(["#", "attack", "target", "expected", "observed", "match", "enforcing mechanism"], [(r["id"], r["attack"], r["target"], r["expected"], r["observed"], r["match"], r["enforcing_mechanism"]) for r in adv])}

Reading the gaps:
- A single key holding the officer, Sharia and ops roles passes every gate. Role separation only helps if the roles sit on different keys or multisigs. The shared test setup and the Deploy script both use one key.
- `repay` takes the repaid amount from the caller. No on-chain check ties it to real collections. A key with `OPS_ROLE` can mature a pool at zero yield, report any amount it funds itself, or default any Active pool alone.
- The document hash is not checked for reuse, so the same hash can back two financings.
- Reentrancy is covered by the repo's own `Reentrancy.t.sol`, which was not rerun because the repo test suite does not compile in the current working tree (see limitations).

## 6. Scale results

Each financing has 3 to 5 funding transactions (seeded pseudo random), then repay and full redemption. Local Cancun gas.

{md(["financings", "fundings", "txs", "total gas", "gas per financing", "register+approve", "fund", "repay", "redeem"], [(r["financings"], r["fundings"], r["txs"], fmt(int(r["total_gas"])), fmt(int(r["gas_per_financing"])), fmt(int(r["register_approve_gas"])), fmt(int(r["fund_gas"])), fmt(int(r["repay_gas"])), fmt(int(r["redeem_gas"]))) for r in scale])}

Per financing gas is flat from 100 to 1000, so no contract level cost growth was observed in this range. `getDeals()` and `getDealsByStatus()` iterate the full array and were not benchmarked.

## 7. Limitations

- All data is synthetic and generated by fixed rules. There is no pilot, no real borrower and no real user.
- No off chain AI agent was run and its accuracy is not measured. The agent signer is modelled only as a role holding key.
- Tranche release, evidence hashing, verification, mismatch handling, escalation and appeal do not exist on-chain, so none of them were measured. Funding gas is only a proxy.
- Gas is from Foundry's Cancun model. Sepolia measurements show a large gap, and Arbitrum was never measured. USD figures use unverified price assumptions and omit the Arbitrum L1 data fee.
- The Sepolia lifecycle used one key for every role and one investor, so it says nothing about role separation.
- The repo's own suite does not compile in the current working tree, because `test/RedemptionVault.t.sol` references `Ownable`, which the contracts no longer use. Reentrancy and other existing tests were not run. The eval profile compiles only `test/eval`.
- Adversarial tests check call level access control and state checks. They are not a security audit, and no fuzzing or formal verification was done.
"""
with open(os.path.join(EVAL, "RESULTS.md"), "w") as f:
    f.write(doc)
print("wrote", os.path.join(EVAL, "RESULTS.md"))
